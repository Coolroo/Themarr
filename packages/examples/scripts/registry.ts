// Read the example folders and make the registry's text. Node only
// (node:fs); scripts/generate.ts writes the text to src/registry.generated.ts.

import { readdirSync, readFileSync } from "node:fs";
import { MODES } from "@themarr/tokens";
import type { Example, ExampleMeta } from "../src/types.ts";
import { lintExample } from "./lint.ts";

export const PKG_DIR = new URL("../", import.meta.url);

/** Folders of the package that are not examples. */
export const NOT_EXAMPLES: ReadonlySet<string> = new Set(["src", "scripts", "test", "node_modules", "dist"]);

/** The files of an example folder, and no others. */
export const EXAMPLE_FILES = ["example.json", "page.css", "page.html"] as const;

export const ID_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const META_KEYS = ["id", "name", "sourceApp", "description", "modes", "size"];
const MAX_SIDE = 4000;

/** The example folders, sorted. */
export function exampleDirs(root: URL = PKG_DIR): string[] {
  return readdirSync(root, { withFileTypes: true })
    .filter((d) => d.isDirectory() && !d.name.startsWith(".") && !NOT_EXAMPLES.has(d.name))
    .map((d) => d.name)
    .sort();
}

function isObject(v: unknown): v is Record<string, unknown> {
  return typeof v === "object" && v !== null && !Array.isArray(v);
}

function isText(v: unknown, max: number): v is string {
  return typeof v === "string" && v.trim() !== "" && v.length <= max;
}

/** The problems in an example.json for the folder `folder`; [] when it is good. */
export function checkMeta(folder: string, v: unknown): string[] {
  if (!isObject(v)) return ["not a JSON object"];
  const p: string[] = [];
  for (const k of Object.keys(v)) if (!META_KEYS.includes(k)) p.push(`unknown field "${k}"`);
  for (const k of META_KEYS) if (!(k in v)) p.push(`missing field "${k}"`);
  if (typeof v["id"] !== "string" || !ID_PATTERN.test(v["id"])) p.push("id: lower-case letters, digits and single hyphens");
  else if (v["id"] !== folder) p.push(`id: must be the folder's name, "${folder}"`);
  if (!isText(v["name"], 80)) p.push("name: 1 to 80 characters");
  if (typeof v["sourceApp"] !== "string" || !ID_PATTERN.test(v["sourceApp"])) p.push("sourceApp: an app ID (a slug)");
  if (!isText(v["description"], 300)) p.push("description: 1 to 300 characters");
  const modes = v["modes"];
  if (
    !Array.isArray(modes) ||
    modes.length === 0 ||
    new Set(modes).size !== modes.length ||
    !modes.every((m) => (MODES as readonly unknown[]).includes(m))
  ) {
    p.push('modes: a non-empty list of "light" and "dark", each once');
  }
  const size = v["size"];
  const side = (n: unknown): boolean => Number.isInteger(n) && (n as number) > 0 && (n as number) <= MAX_SIDE;
  if (!isObject(size) || Object.keys(size).length !== 2 || !side(size["width"]) || !side(size["height"])) {
    p.push(`size: {"width", "height"}, whole pixels from 1 to ${MAX_SIDE}`);
  }
  return p;
}

/** Read one example folder. Throws with every problem when it breaks a rule. */
export function readExample(folder: string, root: URL = PKG_DIR): Example {
  const dir = new URL(`${folder}/`, root);
  const problems: string[] = [];
  const files = readdirSync(dir).sort();
  for (const f of files) if (!(EXAMPLE_FILES as readonly string[]).includes(f)) problems.push(`unexpected file ${f}`);
  for (const f of EXAMPLE_FILES) if (!files.includes(f)) problems.push(`missing ${f}`);
  if (problems.length > 0) throw new Error(`examples/${folder}: ${problems.join("; ")}`);
  let raw: unknown;
  try {
    raw = JSON.parse(readFileSync(new URL("example.json", dir), "utf8"));
  } catch (e) {
    throw new Error(`examples/${folder}/example.json: ${(e as Error).message}`);
  }
  const metaProblems = checkMeta(folder, raw);
  if (metaProblems.length > 0) throw new Error(`examples/${folder}/example.json: ${metaProblems.join("; ")}`);
  const m = raw as ExampleMeta;
  const meta: ExampleMeta = {
    id: m.id,
    name: m.name,
    sourceApp: m.sourceApp,
    description: m.description,
    modes: [...m.modes],
    size: { width: m.size.width, height: m.size.height },
  };
  const html = readFileSync(new URL("page.html", dir), "utf8");
  const css = readFileSync(new URL("page.css", dir), "utf8");
  const lint = lintExample(meta, html, css);
  if (lint.length > 0) throw new Error(`examples/${folder}:\n  ${lint.join("\n  ")}`);
  return { ...meta, html, css };
}

/** Every example, sorted by id. */
export function readExamples(root: URL = PKG_DIR): Example[] {
  return exampleDirs(root).map((d) => readExample(d, root));
}

/** The text of src/registry.generated.ts. */
export function registryText(examples: readonly Example[]): string {
  return [
    "// Generated by scripts/generate.ts from the example folders. Do not edit:",
    "// change a folder, then run `npm run generate -w @themarr/examples`.",
    'import type { Example } from "./types.ts";',
    "",
    `export const EXAMPLES: readonly Example[] = ${JSON.stringify(examples, null, 2)};`,
    "",
  ].join("\n");
}

export const REGISTRY_FILE = new URL("src/registry.generated.ts", PKG_DIR);
